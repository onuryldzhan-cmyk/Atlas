"""
============================================================
ATLAS OS CONFIGURATION-SECRETS BRIDGE v2.0
============================================================

Enterprise-grade integration layer between the AtlasOS
Configuration Service and Secrets Manager.

Core guarantees
---------------
- Configuration stores references, not plaintext secrets.
- Environment variables are the preferred runtime source.
- Plaintext configuration loading is disabled by default.
- Secret values never appear in snapshots, logs, repr output,
  exceptions generated by this module, or bridge metadata.
- SecretsManager remains the single source of truth for secret
  storage, authorization, rotation, masking, validation, and
  access history.
- The bridge adapts safely to the active SecretsManager API and
  forwards only supported registration parameters.
- Binding state is thread-safe and deterministic.

============================================================
"""

from __future__ import annotations

import inspect
import logging
import os

from dataclasses import dataclass, field
from datetime import UTC, datetime
from enum import Enum
from threading import RLock
from types import MappingProxyType
from typing import Any, Mapping, Protocol, runtime_checkable

from atlas_os.secrets import (
    DuplicateSecretError,
    SecretNotFoundError,
    SecretSource,
    SecretsManager,
    SecretValidationError,
    SecretValueMissingError,
)


logger = logging.getLogger(
    "AtlasOS.ConfigurationSecretsBridge"
)


# =========================================================
# ENUMS
# =========================================================


class SecretBindingMode(str, Enum):
    """
    Defines the approved source used to resolve a secret.
    """

    ENVIRONMENT = "ENVIRONMENT"
    CONFIGURATION_REFERENCE = "CONFIGURATION_REFERENCE"
    CONFIGURATION_VALUE = "CONFIGURATION_VALUE"


class SecretBindingStatus(str, Enum):
    """
    Runtime state of a secret binding.
    """

    REGISTERED = "REGISTERED"
    LOADED = "LOADED"
    MISSING = "MISSING"
    INVALID = "INVALID"
    SKIPPED = "SKIPPED"


# =========================================================
# EXCEPTIONS
# =========================================================


class ConfigurationSecretsBridgeError(RuntimeError):
    """
    Base exception for bridge failures.
    """


class SecretBindingNotFoundError(
    ConfigurationSecretsBridgeError
):
    """
    Raised when a requested binding is not registered.
    """


class SecretBindingRegistrationError(
    ConfigurationSecretsBridgeError
):
    """
    Raised when a binding cannot be registered safely.
    """


class ConfigurationValueNotFoundError(
    ConfigurationSecretsBridgeError
):
    """
    Raised when a required configuration value is absent.
    """


class UnsafeSecretConfigurationError(
    ConfigurationSecretsBridgeError
):
    """
    Raised when plaintext secret loading is blocked.
    """


